package com.smartfix.cloud;

import com.smartfix.notification.repository.PostgresNotificationInsertRepository;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import java.time.Clock;
import static org.junit.jupiter.api.Assertions.*;

class DeliveryCompletionServiceTest {
    JdbcTemplate jdbc;
    DeliveryCompletionService service;
    @BeforeEach void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:completion;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE delivery_tasks(id BIGINT PRIMARY KEY, recipient_id BIGINT, channel VARCHAR, event_type VARCHAR, dedup_key VARCHAR, title VARCHAR, message VARCHAR, reference_id BIGINT, status VARCHAR, delivered_at TIMESTAMP, last_error VARCHAR)");
        jdbc.execute("CREATE TABLE notifications(id BIGINT GENERATED BY DEFAULT AS IDENTITY, recipient_id BIGINT, event_type VARCHAR, dedup_key VARCHAR UNIQUE, title VARCHAR, message VARCHAR, reference_id BIGINT, created_at TIMESTAMP)");
        jdbc.update("INSERT INTO delivery_tasks VALUES(1,7,'IN_APP','REQUEST_STATUS_CHANGED','event:1','Update','Resolved',9,'QUEUED',NULL,NULL)");
        service = new DeliveryCompletionService(jdbc, new PostgresNotificationInsertRepository(jdbc),
                new TransactionTemplate(new DataSourceTransactionManager(source)), Clock.systemUTC());
    }
    @Test void replayProducesOneNotificationAndCompletesTask() {
        service.complete(1, "event:1", "DELIVERED");
        service.complete(1, "event:1", "DELIVERED");
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM notifications", Integer.class));
        assertEquals("DELIVERED", jdbc.queryForObject("SELECT status FROM delivery_tasks", String.class));
        assertEquals("Resolved", jdbc.queryForObject("SELECT message FROM notifications", String.class));
    }
    @Test void mismatchedKeyCannotCompleteTask() {
        assertThrows(IllegalArgumentException.class, () -> service.complete(1, "wrong", "DELIVERED"));
        assertEquals("QUEUED", jdbc.queryForObject("SELECT status FROM delivery_tasks", String.class));
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM notifications", Integer.class));
    }
    @Test void sendCommitGapStillAllowsCallback() {
        jdbc.update("UPDATE delivery_tasks SET status='PENDING'");
        service.complete(1, "event:1", "DELIVERED");
        assertEquals("DELIVERED", jdbc.queryForObject("SELECT status FROM delivery_tasks", String.class));
    }
    @Test void inAppCannotBeSilentlySkipped() {
        assertThrows(IllegalArgumentException.class, () -> service.complete(1, "event:1", "SKIPPED"));
    }
    @Test void projectionFailureRollsBackCompletion() {
        jdbc.execute("DROP TABLE notifications");
        assertThrows(RuntimeException.class, () -> service.complete(1, "event:1", "DELIVERED"));
        assertEquals("QUEUED", jdbc.queryForObject("SELECT status FROM delivery_tasks", String.class));
    }
}
