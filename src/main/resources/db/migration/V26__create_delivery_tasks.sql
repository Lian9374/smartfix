CREATE TABLE delivery_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id),
    channel VARCHAR(20) NOT NULL CHECK(channel IN ('IN_APP','EMAIL')),
    event_type VARCHAR(80) NOT NULL,
    dedup_key VARCHAR(200) NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    reference_id BIGINT,
    status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','DELIVERED','FAILED','SKIPPED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    delivered_at TIMESTAMPTZ,
    last_error VARCHAR(100)
);
CREATE INDEX idx_delivery_tasks_due ON delivery_tasks(next_attempt_at,id) WHERE status='PENDING';
