CREATE TABLE sla_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    urgency VARCHAR(20) NOT NULL CHECK(urgency IN ('LOW','MEDIUM','HIGH')),
    phase VARCHAR(20) NOT NULL CHECK(phase IN ('RECEIPT','ASSIGNMENT','RESOLUTION','CONFIRMATION')),
    duration_seconds BIGINT NOT NULL CHECK(duration_seconds > 0 AND duration_seconds <= 31536000),
    reminder_seconds BIGINT NOT NULL CHECK(reminder_seconds >= 0 AND reminder_seconds <= duration_seconds),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(urgency,phase)
);
CREATE TABLE sla_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    phase VARCHAR(20) NOT NULL CHECK(phase IN ('RECEIPT','ASSIGNMENT','RESOLUTION','CONFIRMATION')),
    cycle INTEGER NOT NULL DEFAULT 1 CHECK(cycle>0),
    status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','PAUSED','COMPLETED')),
    duration_seconds BIGINT NOT NULL,
    reminder_seconds BIGINT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    reminder_due_at TIMESTAMPTZ NOT NULL,
    last_event_key VARCHAR(200),
    paused_at TIMESTAMPTZ,
    reminded_at TIMESTAMPTZ,
    breached_at TIMESTAMPTZ,
    UNIQUE(request_id,phase)
);
CREATE INDEX idx_sla_states_active_due ON sla_states(due_at,id) WHERE status='ACTIVE';
