-- Separate transport order from optimistic entity versions. Preserve stage5 event order.
CREATE TABLE community_event_sequences (
 question_id BIGINT PRIMARY KEY REFERENCES community_questions(id), sequence BIGINT NOT NULL
);
INSERT INTO community_event_sequences SELECT question_id, max(aggregate_sequence) FROM community_outbox GROUP BY question_id;
CREATE TABLE community_commands (
 actor_id BIGINT NOT NULL, command_key UUID NOT NULL, operation VARCHAR(50) NOT NULL,
 request_hash VARCHAR(64) NOT NULL, result TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(actor_id,command_key,operation)
);
CREATE TABLE community_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_user_id BIGINT NOT NULL,
 action VARCHAR(80) NOT NULL, target_type VARCHAR(30) NOT NULL, target_id BIGINT NOT NULL,
 outcome VARCHAR(30) NOT NULL, occurred_at TIMESTAMPTZ NOT NULL
);
